<script>
  // تابع برای ایجاد آواتار پیش‌فرض
  function createDefaultAvatar(name) {
    const container = document.createElement('div');
    container.className = 'w-full h-full flex items-center justify-center rounded-full';
    
    // اگر نام وجود داشت، حرف اول نام را نمایش می‌دهیم
    if (name && name.length > 0) {
      const firstLetter = name.charAt(0);
      container.textContent = firstLetter;
      container.className += ' bg-gradient-to-r from-amber-500 to-orange-500 text-white font-bold text-xl';
    } 
    // اگر نام وجود نداشت، آیکون کاربر را نمایش می‌دهیم
    else {
      const icon = document.createElement('i');
      icon.className = 'fas fa-user text-2xl text-white';
      container.appendChild(icon);
      container.className += ' bg-gradient-to-r from-blue-500 to-indigo-500';
    }
    
    return container;
  }

  // تابع برای جایگزینی آواتار خراب با آواتار پیش‌فرض
  function handleAvatarError(imgElement, userName) {
    const container = imgElement.parentNode;
    container.innerHTML = '';
    container.appendChild(createDefaultAvatar(userName));
  }

  // اعمال برای تمام تصاویر آواتار
  document.querySelectorAll('.testimonial-card img').forEach(img => {
    const userName = img.alt || '';
    img.onerror = function() {
      handleAvatarError(img, userName);
    };
    
    // اگر لینک تصویر خالی بود، مستقیماً آواتار پیش‌فرض ایجاد می‌کنیم
    if (!img.src || img.src === window.location.href) {
      handleAvatarError(img, userName);
    }
  });
</script>
